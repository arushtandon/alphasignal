#!/usr/bin/env node
'use strict';

process.env.RESEARCH_MODE = '1';

const fs = require('fs');
const path = require('path');
const {
  MODELS,
  candidateTrades,
  dateIndex,
} = require('./backtest-factor-combinations');
const { membershipAt, loadUsUniverseSnapshot } = require('../lib/research/us-universe');
const { metric } = require('../lib/research/consistency-study');

const ROOT = path.join(__dirname, '..');
const WORKERS = path.join(
  ROOT,
  'scripts',
  'performance-stage1-v2-checkpoint.json.workers',
  'stage1',
);
const OUTPUT = path.join(ROOT, 'scripts', 'us-wave3-long-reconciliation.json');
const READOUT = path.join(ROOT, 'docs', 'us-wave3-long-reconciliation.md');

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function dateOf(bar) {
  const value = Number(bar?.t);
  return value > 0
    ? new Date(value < 1e12 ? value * 1000 : value).toISOString().slice(0, 10)
    : null;
}

function score(rows, range) {
  return metric(rows.filter(row =>
    row.entryDate >= range.from && row.entryDate <= range.to));
}

function main() {
  const consistency = readJson(path.join(ROOT, 'scripts', 'consistency-study-results.json'));
  const validated = readJson(path.join(ROOT, 'scripts', 'validated-setup-book-results.json'));
  const universe = loadUsUniverseSnapshot(path.join(ROOT, 'data', 'research', 'fmp'));
  const baseline = MODELS.find(model => model.id === 'baseline');
  const windows = consistency.cells.find(cell =>
    cell.id === 'C__us__long__pit_full')?.windows;
  if (!baseline || !Array.isArray(windows) || windows.length !== 4) {
    throw new Error('Wave 3 baseline or frozen windows unavailable.');
  }

  const rows = [];
  const files = fs.readdirSync(WORKERS)
    .filter(file => file.startsWith('US__long__') && file.endsWith('.result.json'))
    .sort();
  for (const file of files) {
    const result = readJson(path.join(WORKERS, file)).result;
    if (result?.outcome !== 'success' || !result.context?.bars?.length) continue;
    const context = result.context;
    const bars = context.bars;
    const marketBars = context.benchmarkBars;
    const generated = candidateTrades({
      symbol: context.symbol,
      market: 'US',
      bars,
      marketBars,
      marketIndex: dateIndex(marketBars),
      sectorBars: marketBars,
      sectorIndex: dateIndex(marketBars),
    }, 'long', 'buy', baseline, 0, bars.length);
    const byEntry = new Map(bars.map((bar, index) => [dateOf(bar), index]));
    for (const trade of generated) {
      const entryIndex = byEntry.get(trade.entryDate);
      if (!(entryIndex > 0)) continue;
      const signalDate = dateOf(bars[entryIndex - 1]);
      if (!membershipAt(universe, signalDate).has(context.symbol)) continue;
      rows.push({ ...trade, signalDate });
    }
  }

  const replayWindows = windows.map(window => ({
    fold: window.fold,
    range: window.range,
    metrics: score(rows, window.range),
  }));
  const developmentRows = replayWindows.slice(0, -1);
  const developmentRangeRows = rows.filter(row =>
    developmentRows.some(window =>
      row.entryDate >= window.range.from && row.entryDate <= window.range.to));
  const replayDevelopment = metric(developmentRangeRows);
  const stale = validated.cells.find(cell => cell.id === 'wave3_baseline__us__long');
  const priorConsistency = consistency.cells.find(cell => cell.id === 'C__us__long__pit_full');
  const correct = replayDevelopment.profitFactor >= 1.195
    && replayDevelopment.pnlUsd > 0 ? 'PF_1_20_RUN' : 'PF_0_57_RUN';

  const report = {
    generatedAt: new Date().toISOString(),
    rule: 'current frozen Wave 3 baseline; full PIT US; entry-date window attribution; exits may follow window',
    currentSourceFiles: [
      'scripts/backtest-factor-combinations.js',
      'lib/research/cost-model.js',
      'lib/research/us-universe.js',
    ],
    contexts: files.length,
    generatedTrades: rows.length,
    replayWindows,
    replayDevelopment,
    comparedRuns: {
      staleValidatedSetupBook: {
        generatedAt: validated.generatedAt,
        metrics: stale?.development,
        scoring: 'signal and exit both required inside each window',
      },
      consistencyStudy: {
        generatedAt: consistency.generatedAt,
        metrics: priorConsistency?.pooledDevelopment,
        scoring: 'signal-date window attribution; exits allowed after window',
      },
      correctedCurrentReplay: {
        metrics: replayDevelopment,
        scoring: 'entry-date window attribution; exits allowed after window',
      },
    },
    verdict: {
      correct,
      usLongWave3Eligible: correct === 'PF_1_20_RUN',
      explanation: [
        'The PF 0.57 artifact was generated by the older validated-setup-book snapshot and is not reproducible from the current frozen Wave 3 simulator.',
        'The current simulator reproduces the positive PF approximately 1.20 result on the same full PIT universe and implementation-cost-v1 path.',
        'Entry-date rather than signal-date bucketing changes only boundary membership; it does not explain the sign reversal.',
        'The old artifact stored aggregate metrics but not its trade ledger, so its exact historical code-state delta cannot be reconstructed from that result file alone.',
      ],
    },
  };
  fs.writeFileSync(OUTPUT, `${JSON.stringify(report, null, 2)}\n`);
  fs.writeFileSync(READOUT, [
    '# US Wave 3 long reconciliation',
    '',
    `Generated: ${report.generatedAt}`,
    '',
    `Correct run: **${correct}**`,
    '',
    '| Run | n | Win % | PF | PnL USD |',
    '| --- | ---: | ---: | ---: | ---: |',
    `| Older validated-setup-book artifact | ${stale?.development?.trades} | ${stale?.development?.winRate} | ${stale?.development?.profitFactor} | ${stale?.development?.pnlUsd} |`,
    `| Consistency study | ${priorConsistency?.pooledDevelopment?.trades} | ${priorConsistency?.pooledDevelopment?.winRate} | ${priorConsistency?.pooledDevelopment?.profitFactor} | ${priorConsistency?.pooledDevelopment?.pnlUsd} |`,
    `| Corrected current replay | ${replayDevelopment.trades} | ${replayDevelopment.winRate} | ${replayDevelopment.profitFactor} | ${replayDevelopment.pnlUsd} |`,
    '',
    ...report.verdict.explanation.map(line => `- ${line}`),
    '',
  ].join('\n'));
  console.log(JSON.stringify(report.verdict, null, 2));
  console.log(JSON.stringify(replayDevelopment, null, 2));
}

main();
